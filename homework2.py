# Напишіть промпт для створення плану навчального
# курсу з певної теми для цільової аудиторії (початківці, професіонали, діти тощо).
# Вхідні параметри: тема, опис цільової аудиторії
# Реалізуйте двома способами: Zero-shot і Few-shot

from langchain_google_genai import GoogleGenerativeAI
from langchain_core.prompts import PromptTemplate
import os
import dotenv


dotenv.load_dotenv()
api_key = os.getenv("GEMINI_API_KEY")

llm = GoogleGenerativeAI(
    model="gemini-3.5-flash-lite",
    api_key=api_key,
)

prompt = PromptTemplate.from_template("""
Ти — помічник-інструктор. Створи план навчального курсу по темі: {topic} для аудиторії: {audience}.

##ВИМОГИ###
1. Дай короткий опис курсу (1-2 речення).
2. Розбий курс на 6 модулів/тижнів (або менше, якщо доречно).
3. Для кожного модуля вкажи: назву, цілі навчання (2-3 пункти), тривалість у годинах, рекомендовані ресурси.
4. Зазнач необхідні попередні знання.
5. Підкажи рівень складності і цільову аудиторію.

### ПРИКЛАД 1
Тема: Python для початківців
Аудиторія: Початківці, без досвіду
Короткий опис: Курс ознайомлює з базовими концепціями Python — синтаксис, структури даних, робота з файлами.
Модуль 1: Вступ до Python
- Цілі: встановити середовище, знати синтаксис
- Тривалість: 2 години
- Ресурси: офіційна документація, Python tutorial

Модуль 2: Змінні та типи
- Цілі: розуміти типи, операції
- Тривалість: 3 години
- Ресурси: офіційна документація

### ПРИКЛАД 2
Тема: Веб-розробка (Frontend)
Аудиторія: Новачки з основами HTML/CSS
Короткий опис: Основи JavaScript та робота з DOM для створення інтерактивних сторінок.
Модуль 1: Основи JavaScript
- Цілі: синтаксис, змінні, функції
- Тривалість: 3 години
- Ресурси: MDN

Тепер склади план для запиту нижче.

Формат відповіді: як у прикладах — короткий опис і модулі з перерахованими цілями, тривалістю і ресурсами.
""")




data = {
    "topic":"Python для початківців",
    "audience":"Початківці"
}

text = prompt.invoke(data)

response = llm.invoke(text)
print(response)